const guard = (
	what: string,
	only: string,
	file: string,
	from: string,
	to: string,
): ReleaseBreak => ({
	what,
	check: "guard",
	only,
	says: new RegExp(
		`check:guard failed: .*${only.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`,
	),
	file,
	from,
	to,
});
const load = (
	what: string,
	says: RegExp,
	file: string,
	from: string,
	to: string,
): ReleaseBreak => ({ what, check: "load", says, file, from, to });
const release = (
	what: string,
	only: string,
	file: string,
	from: string,
	to: string,
	shows?: RegExp,
): ReleaseBreak => ({
	what,
	check: "release",
	only,
	says: new RegExp(
		`check:release failed: .*${only.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`,
	),
	shows,
	file,
	from,
	to,
});
/** A break of the workflows or the tree: the facts are read first, whatever runs. */
const facts = (
	what: string,
	says: RegExp,
	file: string,
	from: string,
	to: string,
): ReleaseBreak => ({
	what,
	check: "release",
	only: "facts",
	says,
	file,
	from,
	to,
});

