import fs from "node:fs";
import ts from "typescript";

function walk(dir) {
	return fs
		.readdirSync(dir, { withFileTypes: true })
		.flatMap((e) =>
			e.isDirectory() ? walk(`${dir}/${e.name}`) : [`${dir}/${e.name}`],
		);
}
const factories = {
	defineRead: ["read", "public"],
	defineWrite: ["write", "public"],
	defineTask: ["task", "public"],
	privateRead: ["read", "internal"],
	privateWrite: ["write", "internal"],
	privateTask: ["task", "internal"],
};
const endpoints = [];
for (const file of walk("server").filter(
	(file) => /\.ts$/.test(file) && !/\/api.ts$|\/registry.ts$/.test(file),
)) {
	const source = ts.createSourceFile(
		file,
		fs.readFileSync(file, "utf8"),
		ts.ScriptTarget.Latest,
		true,
	);
	for (const statement of source.statements) {
		if (
			!ts.isVariableStatement(statement) ||
			!statement.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
		)
			continue;
		for (const d of statement.declarationList.declarations) {
			if (!d.initializer || !ts.isCallExpression(d.initializer)) continue;
			const factory = d.initializer.expression.getText(source);
			const spec = Object.hasOwn(factories, factory)
				? factories[factory]
				: undefined;
			if (spec)
				endpoints.push({
					module: file.replace(/^server\//, "").replace(/\.ts$/, ""),
					name: d.name.getText(source),
					kind: spec[0],
					visibility: spec[1],
				});
		}
	}
}
function tree(list) {
	const root = {};
	for (const e of list) {
		let node = root;
		const parts = e.module.split("/");
		for (const part of parts) node = node[part] ??= {};
		node[e.name] =
			`reference<ArgsOf<typeof import("./${e.module}").${e.name}>, ResultOf<typeof import("./${e.module}").${e.name}>>("${e.module}:${e.name}", "${e.kind}")`;
	}
	const print = (node) =>
		`{${Object.entries(node)
			.map(
				([k, v]) =>
					`${JSON.stringify(k)}:${typeof v === "string" ? v : print(v)}`,
			)
			.join(",\n")}}`;
	return print(root);
}
fs.writeFileSync(
	"server/api.ts",
	`// Generated by scripts/generate-api.mjs; contains no server implementation imports.\nimport { reference, type ArgsOf, type ResultOf } from "./contract";\nexport const api = ${tree(endpoints.filter((e) => e.visibility === "public"))};\nexport const internal = ${tree(endpoints.filter((e) => e.visibility === "internal"))};\n`,
);
const modules = [...new Set(endpoints.map((e) => e.module))];
fs.writeFileSync(
	"server/registry.ts",
	`// Generated by scripts/generate-api.mjs. Server-only.\n${modules.map((m, i) => `import * as m${i} from "./${m}";`).join("\n")}\nexport const registry = {\n${endpoints.map((e) => `${JSON.stringify(`${e.module}:${e.name}`)}:m${modules.indexOf(e.module)}.${e.name}`).join(",\n")}\n};\n`,
);
console.log(`Generated ${endpoints.length} typed procedure references.`);
